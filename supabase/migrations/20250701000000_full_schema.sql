-- 4. FUNCTIONS & TRIGGERS

-- Auto create profile on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, avatar_url)
  VALUES (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'avatar_url');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Auto update updated_at
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_updated_at_customers BEFORE UPDATE ON public.customers FOR EACH ROW EXECUTE PROCEDURE public.handle_updated_at();

-- Stock management functions
CREATE OR REPLACE FUNCTION public.decrement_stock(p_product_id BIGINT, p_quantity INTEGER, p_variant_id UUID DEFAULT NULL)
RETURNS VOID AS $$
BEGIN
    IF p_variant_id IS NOT NULL THEN
        UPDATE public.product_variants
        SET stock_quantity = stock_quantity - p_quantity
        WHERE id = p_variant_id;
    ELSE
        UPDATE public.products
        SET stock_quantity = stock_quantity - p_quantity
        WHERE id = p_product_id;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to automatically decrement stock when order is sent/completed
CREATE OR REPLACE FUNCTION public.trigger_decrement_stock_on_order_status()
RETURNS TRIGGER AS $$
DECLARE
    item RECORD;
BEGIN
    -- Check if status changed to 'enviado' or 'concluido'
    IF (NEW.status = 'enviado' OR NEW.status = 'concluido') AND (OLD.status != 'enviado' AND OLD.status != 'concluido') THEN
        IF NEW.items IS NOT NULL AND jsonb_array_length(NEW.items) > 0 THEN
            FOR item IN SELECT * FROM jsonb_to_recordset(NEW.items) AS x(product_id BIGINT, quantity INTEGER, variant_id UUID)
            LOOP
                PERFORM public.decrement_stock(item.product_id, item.quantity, item.variant_id);
            END LOOP;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER tr_decrement_stock_on_order_status
    AFTER UPDATE ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION public.trigger_decrement_stock_on_order_status();

-- 5. STORAGE
INSERT INTO storage.buckets (id, name, public) 
VALUES ('products', 'products', true)
ON CONFLICT (id) DO NOTHING;

-- Storage Policies
CREATE POLICY "Public Access" ON storage.objects FOR SELECT USING (bucket_id = 'products');
CREATE POLICY "Authenticated users can upload images" ON storage.objects FOR INSERT 
    WITH CHECK (bucket_id = 'products' AND auth.role() = 'authenticated');
CREATE POLICY "Users can update their own images" ON storage.objects FOR UPDATE 
    USING (bucket_id = 'products' AND auth.uid() = owner);
CREATE POLICY "Users can delete their own images" ON storage.objects FOR DELETE 
    USING (bucket_id = 'products' AND auth.uid() = owner);
